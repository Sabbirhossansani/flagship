-- V2__phase3_advanced_features.sql
-- Change Control (Audit History, Change Requests, Scheduled Changes) and Experiments

CREATE TABLE flag_change_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_key VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL,
    author VARCHAR(150) NOT NULL,
    reason TEXT NOT NULL,
    action VARCHAR(50) NOT NULL,
    before_json TEXT,
    after_json TEXT,
    diff_summary TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_change_history_entity ON flag_change_history(project_key, env_key, entity_type, entity_key);

CREATE TABLE change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_key VARCHAR(100) NOT NULL,
    action VARCHAR(50) NOT NULL,
    payload_json TEXT NOT NULL,
    author VARCHAR(150) NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    approved_by VARCHAR(150),
    approved_at TIMESTAMP WITH TIME ZONE,
    rejection_reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_change_requests_env_status ON change_requests(project_key, env_key, status);

CREATE TABLE scheduled_flag_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    flag_key VARCHAR(100) NOT NULL,
    action VARCHAR(50) NOT NULL,
    payload_json TEXT NOT NULL,
    author VARCHAR(150) NOT NULL,
    reason TEXT NOT NULL,
    scheduled_time TIMESTAMP WITH TIME ZONE NOT NULL,
    executed BOOLEAN NOT NULL DEFAULT FALSE,
    executed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_scheduled_changes_pending ON scheduled_flag_changes(executed, scheduled_time);

CREATE TABLE experiment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    flag_key VARCHAR(100) NOT NULL,
    variation_key VARCHAR(100),
    metric_name VARCHAR(100),
    user_key VARCHAR(255) NOT NULL,
    event_value DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_exp_events_query ON experiment_events(project_key, env_key, flag_key, event_type);

CREATE TABLE experiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    experiment_key VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    flag_key VARCHAR(100) NOT NULL,
    metric_name VARCHAR(100) NOT NULL,
    baseline_variation_key VARCHAR(100) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_experiments_key UNIQUE (project_key, env_key, experiment_key)
);

CREATE INDEX idx_experiments_env ON experiments(project_key, env_key);
