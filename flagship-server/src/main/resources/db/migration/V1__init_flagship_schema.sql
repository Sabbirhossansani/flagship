-- V1__init_flagship_schema.sql
-- FlagShip Platform Core Schema (Projects, Environments, Segments, Flags, RBAC Role Assignments)

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_projects_key UNIQUE (project_key)
);

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    revision BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_environments_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT uk_environments_project_env UNIQUE (project_id, env_key)
);

CREATE INDEX idx_environments_project_id ON environments(project_id);

CREATE TABLE segments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    segment_key VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    condition_json TEXT,
    included_users_json TEXT NOT NULL,
    excluded_users_json TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_segments_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT fk_segments_environment FOREIGN KEY (project_id, env_key) REFERENCES environments(project_id, env_key) ON DELETE CASCADE,
    CONSTRAINT uk_segments_project_env_key UNIQUE (project_id, env_key, segment_key)
);

CREATE INDEX idx_segments_project_env ON segments(project_id, env_key);

CREATE TABLE flags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    env_key VARCHAR(100) NOT NULL,
    flag_key VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    owner VARCHAR(255) NOT NULL DEFAULT 'unassigned',
    variation_type VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    kill_switch BOOLEAN NOT NULL DEFAULT FALSE,
    variations_json TEXT NOT NULL,
    default_variation_key VARCHAR(100) NOT NULL,
    off_variation_key VARCHAR(100) NOT NULL,
    individual_targets_json TEXT NOT NULL,
    rules_json TEXT NOT NULL,
    rollout_percentage DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    rollout_variation_key VARCHAR(100),
    percentage_rollout_json TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_evaluated_at TIMESTAMP WITH TIME ZONE,
    full_rollout_since TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_flags_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT fk_flags_environment FOREIGN KEY (project_id, env_key) REFERENCES environments(project_id, env_key) ON DELETE CASCADE,
    CONSTRAINT uk_flags_project_env_key UNIQUE (project_id, env_key, flag_key)
);

CREATE INDEX idx_flags_project_env ON flags(project_id, env_key);

CREATE TABLE project_role_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(100) NOT NULL,
    username VARCHAR(150) NOT NULL,
    role VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_role_project FOREIGN KEY (project_key) REFERENCES projects(project_key) ON DELETE CASCADE,
    CONSTRAINT uk_project_role_user UNIQUE (project_key, username)
);

CREATE INDEX idx_project_role_project_key ON project_role_assignments(project_key);
CREATE INDEX idx_project_role_username ON project_role_assignments(username);
